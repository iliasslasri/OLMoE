# ── Main ───────────────────────────────────────────────────────────────────────

def main():
    out_dir = Path("configs/grid")
    out_dir.mkdir(parents=True, exist_ok=True)

    manifest_rows = []
    total_gpu_hours = 0.0

    # Rough FLOPs/s on P100 fp32: ~10 TFLOP/s = 1e13 FLOPs/s
    P100_FP32_FLOPS = 10e12

    for d_model, n_heads in D_MODELS:
        microbatch_size = MICROBATCH[d_model]
        for D_label, D in TOKEN_CONFIGS:
            for G in G_VALUES:
                n_experts = 8 * G
                d_expert  = (4 * d_model) // G
                for j in J_VALUES:
                    top_k  = j * G
                    A      = j / 8

                    steps  = D // BATCH_TOKENS
                    warmup = max(10, math.ceil(0.01 * steps))

                    C  = compute_C(d_model, n_experts, top_k, d_expert, D)
                    lr = A_ETA * C ** (-BETA_ETA)

                    N_act = compute_N_act(d_model, j)
                    N_tot = compute_N_tot(d_model, n_experts, d_expert)

                    # Filename: d{DIM:03d}_G{G:02d}_A{j}_{TLABEL}.yml
                    run_name = f"d{d_model:03d}_G{G:02d}_A{j}_{D_label}"
                    yaml_path = out_dir / f"{run_name}.yml"

                    yaml_content = YAML_TEMPLATE.format(
                        run_name=run_name,
                        d_model=d_model,
                        n_heads=n_heads,
                        N_LAYERS=N_LAYERS,
                        SEQ_LEN=SEQ_LEN,
                        VOCAB_SIZE=VOCAB_SIZE,
                        EMBEDDING_SIZE=EMBEDDING_SIZE,
                        G=G,
                        j=j,
                        A=A,
                        D_label=D_label,
                        n_experts=n_experts,
                        top_k=top_k,
                        d_expert=d_expert,
                        steps=steps,
                        warmup=warmup,
                        C=C,
                        lr=lr,
                        N_act=N_act,
                        N_tot=N_tot,
                        microbatch_size=microbatch_size,
                    )
                    yaml_path.write_text(yaml_content)

                    gpu_hours = (C / P100_FP32_FLOPS) / 3600
                    total_gpu_hours += gpu_hours

                    manifest_rows.append(dict(
                        run_name=run_name,
                        d_model=d_model,
                        n_layers=N_LAYERS,
                        G=G,
                        j=j,
                        A=A,
                        top_k=top_k,
                        n_experts=n_experts,
                        d_expert=d_expert,
                        N_act=N_act,
                        N_tot=N_tot,
                        D=D,
                        steps=steps,
                        warmup=warmup,
                        C=C,
                        lr=lr,
                    ))

    # Write manifest
    manifest_path = out_dir / "manifest.csv"
    fields = ["run_name", "d_model", "n_layers", "G", "j", "A",
              "top_k", "n_experts", "d_expert", "N_act", "N_tot",
              "D", "steps", "warmup", "C", "lr"]
    with open(manifest_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(manifest_rows)
    print(f"Wrote {manifest_path}  ({len(manifest_rows)} rows)")

    # Print summary table
    print(f"\n{'run_name':<30} {'d':>4} {'G':>4} {'j':>3} {'A':>6} "
          f"{'top_k':>6} {'n_exp':>6} {'d_exp':>6} "
          f"{'N_act':>10} {'C':>12} {'lr':>10}")
    print("-" * 100)
    for r in manifest_rows:
        print(f"{r['run_name']:<30} {r['d_model']:>4} {r['G']:>4} {r['j']:>3} "
              f"{r['A']:>6.1%} {r['top_k']:>6} {r['n_experts']:>6} "
              f"{r['d_expert']:>6} {r['N_act']:>10.3e} {r['C']:>12.3e} "
              f"{r['lr']:>10.4e}")

    print(f"\nTotal configs: {len(manifest_rows)}")
    print(f"Total estimated GPU-hours (P100 fp32 @10 TFLOP/s peak): {total_gpu_hours:.1f} h")
    print(f"  NOTE: actual throughput at bs=2 is ~10x below peak (memory-bandwidth bound)")
    print(f"  Realistic estimate: ~{total_gpu_hours*10:.0f} GPU-hours, "
          f"~{total_gpu_hours*10/3:.0f} h wall-clock on 3 GPUs")

    # ── Long runs: d8/d16/d32 configs targeting ≥ 10^15 FLOPs ───────────────────
    long_rows = []
    for d_model, n_heads in D_MODELS:
        if d_model not in LONG_TOKEN_CONFIG:
            continue
        D_label, D = LONG_TOKEN_CONFIG[d_model]
        excluded_g = LONG_G_EXCLUDE.get(d_model, set())
        microbatch_size = MICROBATCH[d_model]
        steps  = D // BATCH_TOKENS
        warmup = max(10, math.ceil(0.01 * steps))

        for G in G_VALUES:
            if G in excluded_g:
                continue
            n_experts = 8 * G
            d_expert  = (4 * d_model) // G
            for j in J_VALUES:
                top_k = j * G
                A     = j / 8
                C     = compute_C(d_model, n_experts, top_k, d_expert, D)
                lr    = A_ETA * C ** (-BETA_ETA)
                N_act = compute_N_act(d_model, j)
                N_tot = compute_N_tot(d_model, n_experts, d_expert)

                run_name  = f"d{d_model:03d}_G{G:02d}_A{j}_{D_label}"
                yaml_path = out_dir / f"{run_name}.yml"
                yaml_path.write_text(YAML_TEMPLATE.format(
                    run_name=run_name, d_model=d_model, n_heads=n_heads,
                    N_LAYERS=N_LAYERS, SEQ_LEN=SEQ_LEN, VOCAB_SIZE=VOCAB_SIZE,
                    EMBEDDING_SIZE=EMBEDDING_SIZE, G=G, j=j, A=A,
                    D_label=D_label, n_experts=n_experts, top_k=top_k,
                    d_expert=d_expert, steps=steps, warmup=warmup, C=C,
                    lr=lr, N_act=N_act, N_tot=N_tot,
                    microbatch_size=microbatch_size,
                ))
                long_rows.append(dict(
                    run_name=run_name, d_model=d_model, G=G, j=j, A=A,
                    D=D, steps=steps, C=C,
                ))

    print(f"\nLong-run configs written: {len(long_rows)}")
    for d_model in sorted({r['d_model'] for r in long_rows}):
        subset = [r for r in long_rows if r['d_model'] == d_model]
        label, D = LONG_TOKEN_CONFIG[d_model]
        cmin = min(r['C'] for r in subset)
        cmax = max(r['C'] for r in subset)
        t_h  = cmin / (0.006 * 10e12) / 3600
        print(f"  d{d_model:3d}  {label}  {len(subset):2d} configs  "
              f"C=[{cmin:.2e},{cmax:.2e}]  ~{t_h:.1f}h/run @MFU=0.006")


if __name__ == "__main__":
    main()
