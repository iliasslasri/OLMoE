#!/usr/bin/env python3
"""generate_grid_configs.py — Generate 400 YAML configs for MoE scaling law Phase 1.

Grid axes:
  d_model ∈ {64, 128, 192, 256}
  D       ∈ {500K, 1M, 2M, 4M}
  G       ∈ {1, 2, 4, 8, 16}       (granularity: n_experts = 8G, d_expert = 4d/G)
  j       ∈ {1, 2, 3, 4, 8}        (top_k = j*G, A = j/8)

Usage:
    python generate_grid_configs.py
"""

import csv
import json
import math
from pathlib import Path

# ── LR scaling law ─────────────────────────────────────────────────────────────

LR_PARAMS_PATH = "results/lr_params.json"
try:
    with open(LR_PARAMS_PATH) as f:
        _p = json.load(f)
    A_ETA    = float(_p["A_eta"])
    BETA_ETA = float(_p["beta_eta"])
    print(f"Loaded LR params from {LR_PARAMS_PATH}: A_eta={A_ETA}, beta_eta={BETA_ETA}")
except FileNotFoundError:
    print(f"WARNING: {LR_PARAMS_PATH} not found — using fallback A_eta=0.5, beta_eta=0.12")
    A_ETA    = 0.5
    BETA_ETA = 0.12

# ── Fixed architecture ──────────────────────────────────────────────────────────

N_LAYERS       = 10
SEQ_LEN        = 1024
VOCAB_SIZE     = 50280
EMBEDDING_SIZE = 50304
BATCH_TOKENS   = 8192  # 8 seqs × 1024

# ── Grid axes ──────────────────────────────────────────────────────────────────

D_MODELS = [
    (8,   1),
    (16,  1),
    (32,  1),
    (64,  1),
    (128, 2),
    (192, 3),
    (256, 4),
]

# device_train_microbatch_size per d_model
# d=8: full batch (8 seqs) fits in one pass
# d=64/128: 4 seqs per microstep (2 grad-accum steps)
# others: keep 1 (conservative for large models on P100)
MICROBATCH = {8: 8, 16: 1, 32: 1, 64: 4, 128: 4, 192: 1, 256: 1}

TOKEN_CONFIGS = [
    ("T0_5M", 500_000),
    ("T1M",   1_000_000),
    ("T2M",   2_000_000),
    ("T4M",   4_000_000),
    ("T8M",   8_000_000),
    ("T16M",  16_000_000),
]

# Long runs — one large D per d_model targeting ≥ 10^15 FLOPs at MFU=0.006 (~4.6 h/run)
# C_min/D (G=1, j=1):  d8→3.46e6,  d16→7.05e6,  d32→1.46e7
# D needed for 10^15:  d8→289M,    d16→142M,     d32→69M
LONG_TOKEN_CONFIG = {
    8:  ("T300M", 300_000_000),
    16: ("T150M", 150_000_000),
    32: ("T75M",   75_000_000),
}
LONG_G_EXCLUDE = {8: {16}}   # G=16 → d_expert=2 for d8, skip

G_VALUES = [1, 2, 4, 8, 16]
J_VALUES = [1, 2, 3, 4, 8]    # top_k = j*G, A = j/8


# ── FLOPs computation ──────────────────────────────────────────────────────────

def compute_C(d_model, n_experts, top_k, d_expert, D):
    """Total training FLOPs — exact per-token formula × D tokens × 3 (fwd+bwd)."""
    c_attn   = 8 * d_model**2 + 4 * SEQ_LEN * d_model
    c_ffn    = 6 * top_k * d_model * d_expert
    c_router = 2 * d_model * n_experts
    m_fwd    = N_LAYERS * (c_attn + c_ffn + c_router) + 2 * d_model * VOCAB_SIZE
    return 3 * m_fwd * D


def compute_N_act(d_model, j):
    """Active parameters per token (independent of G).
    N_act_per_layer = 4d² (attn) + 12·j·d² (FFN active, G cancels)
    """
    return (4 + 12 * j) * d_model**2 * N_LAYERS


def compute_N_tot(d_model, n_experts, d_expert):
    """Total parameters (embedding counted once; weight_tying=True)."""
    n_attn   = 4 * N_LAYERS * d_model**2          # Q, K, V, O per layer
    n_ffn    = N_LAYERS * n_experts * 3 * d_model * d_expert  # SwiGLU: 3 mats
    n_router = N_LAYERS * d_model * n_experts
    n_embed  = EMBEDDING_SIZE * d_model            # shared embed + head
    return n_attn + n_ffn + n_router + n_embed


