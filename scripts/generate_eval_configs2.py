# ── Main ───────────────────────────────────────────────────────────────────────

def main():
    base_dir = Path("configs/eval2")
    for g in ("D", "E", "F"):
        (base_dir / g).mkdir(parents=True, exist_ok=True)

    manifest_rows   = []
    total_gpu_hours = 0.0
    group_counts    = {"D": 0, "E": 0, "F": 0}

    print(f"\n{'run_name':<46} {'d':>4} {'G':>3} {'j':>2} {'A':>6} "
          f"{'steps':>6} {'C_actual':>12} {'~h':>6} {'grp':>4}")
    print("-" * 100)

    seen = set()
    for d_model, n_heads, G, j, C_target, group_label in EVAL_POINTS:
        n_experts = 8 * G
        top_k     = j * G
        d_expert  = (4 * d_model) // G
        A         = j / 8

        m_fwd  = m_fwd_per_token(d_model, n_experts, top_k, d_expert)
        D_raw  = C_target / (3 * m_fwd)
        steps  = max(10, int(D_raw // BATCH_TOKENS))
        D      = steps * BATCH_TOKENS

        warmup    = max(50, math.ceil(0.01 * steps))
        C_actual  = compute_C(d_model, n_experts, top_k, d_expert, D)
        lr        = A_ETA * C_actual ** (-BETA_ETA)
        N_act     = compute_N_act(d_model, j)
        N_tot     = compute_N_tot(d_model, n_experts, d_expert)
        est_hours = C_actual / P100_REALISTIC_FLOPS / 3600

        run_name = f"eval2_d{d_model:04d}_G{G:02d}_A{j}_S{steps}"

        if run_name in seen:
            print(f"  [skip duplicate] {run_name}")
            continue
        seen.add(run_name)

        yaml_path = base_dir / group_label / f"{run_name}.yml"
        yaml_path.write_text(YAML_TEMPLATE.format(
            run_name=run_name, group_label=group_label, C_target=C_target,
            d_model=d_model, n_heads=n_heads,
            N_LAYERS=N_LAYERS, SEQ_LEN=SEQ_LEN,
            VOCAB_SIZE=VOCAB_SIZE, EMBEDDING_SIZE=EMBEDDING_SIZE,
            G=G, j=j, A=A,
            n_experts=n_experts, top_k=top_k, d_expert=d_expert,
            steps=steps, warmup=warmup,
            C_actual=C_actual, lr=lr,
            N_act=N_act, N_tot=N_tot, est_hours=est_hours,
        ))

        total_gpu_hours += est_hours
        group_counts[group_label] += 1

        manifest_rows.append(dict(
            run_name=run_name, group=group_label, C_target=C_target,
            d_model=d_model, n_heads=n_heads, G=G, j=j, A=A,
            top_k=top_k, n_experts=n_experts, d_expert=d_expert,
            N_act=N_act, N_tot=N_tot, D=D,
            steps=steps, warmup=warmup, C_actual=C_actual, lr=lr,
            est_hours=est_hours,
        ))
        print(f"{run_name:<46} {d_model:>4} {G:>3} {j:>2} {A:>6.1%} "
              f"{steps:>6} {C_actual:>12.3e} {est_hours:>6.1f} {group_label:>4}")

    # ── Manifest CSV ──────────────────────────────────────────────────────────
    manifest_path = base_dir / "manifest.csv"
    fields = ["run_name", "group", "C_target", "d_model", "n_heads",
              "G", "j", "A", "top_k", "n_experts", "d_expert",
              "N_act", "N_tot", "D", "steps", "warmup",
              "C_actual", "lr", "est_hours"]
    with open(manifest_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(manifest_rows)

    # ── Summary ───────────────────────────────────────────────────────────────
    print(f"\n{'═'*60}")
    print(f"Phase-2 eval configs written → {base_dir}/")
    print(f"Manifest → {manifest_path}")
    print()
    print(f"  Group D ({group_counts['D']} runs, C≈2e16): "
          f"~{group_counts['D'] * 2e16 / P100_REALISTIC_FLOPS / 3600:.0f} total GPU-h")
    print(f"  Group E ({group_counts['E']} runs, C≈5e16): "
          f"~{group_counts['E'] * 5e16 / P100_REALISTIC_FLOPS / 3600:.0f} total GPU-h")
    print(f"  Group F ({group_counts['F']} runs, C≈1e17): "
          f"~{group_counts['F'] * 1e17 / P100_REALISTIC_FLOPS / 3600:.0f} total GPU-h")
    print(f"  Total: ~{total_gpu_hours:.0f} GPU-h")
    print()

    # ── Isocompute groups ─────────────────────────────────────────────────────
    print("Isocompute groups (configs at same C_target):")
    by_group = {}
    for r in manifest_rows:
        by_group.setdefault(r["group"], []).append(r)
    for gl in ("D", "E", "F"):
        if gl not in by_group:
            continue
        print(f"\n  Group {gl} (C_target={by_group[gl][0]['C_target']:.1e}, "
              f"~{by_group[gl][0]['est_hours']:.0f} h each):")
        print(f"  {'run_name':<42} {'d':>4} {'G':>3} {'j':>2} "
              f"{'steps':>6} {'N_act':>10} {'C_actual':>12}")
        for r in by_group[gl]:
            print(f"    {r['run_name']:<42} {r['d_model']:>4} {r['G']:>3} "
                  f"{r['j']:>2} {r['steps']:>6} {r['N_act']:>10.2e} "
                  f"{r['C_actual']:>12.3e}")

    # ── Launch instructions ───────────────────────────────────────────────────
    print(f"\n{'─'*60}")
    print("Launch instructions (one SLURM array per group):")
    for gl in ("D", "E", "F"):
        if gl not in by_group:
            continue
        n = len(by_group[gl])
        print(f"\n  Group {gl} ({n} runs):")
        print(f"    ls configs/eval2/{gl}/*.yml | head -1  # sanity check")
        print(f"    for cfg in configs/eval2/{gl}/*.yml; do")
        print(f"        sbatch launch_single.slurm $cfg")
        print(f"    done")
        print(f"  # or as array:")
        print(f"    sbatch --array=0-{n-1} launch_array.slurm configs/eval2/{gl}")

    print(f"\nW&B group for these runs: grid_eval2")
    print("To fetch in analyze_grid.py, add --eval-wandb2 flag or manually pass")
    print("group='grid_eval2' to fetch_eval_from_wandb().")


if __name__ == "__main__":
    main()
