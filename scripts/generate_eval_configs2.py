#!/usr/bin/env python3
"""generate_eval_configs2.py — Phase-2 large-scale isocompute validation.

Design goals vs phase 1:
  - d_model ∈ {768, 1024, 1280}  (well beyond phase-1 grid d≤256 and eval d≤512)
  - Low activation ratio: j=1 (A=12.5%), one j=2 (A=25%) point per group
  - Granularity: G=4 and G=8 (phase 1 only tested G=1 and G=2 in eval)
  - Multi-hour runs: realistic P100 time ≈ 5 h / 14 h / 28 h per group

Three independent groups (launch as separate SLURM arrays):
  Group D  C ≈ 2×10¹⁶  ~5 h each   configs/eval2/D/
  Group E  C ≈ 5×10¹⁶  ~14 h each  configs/eval2/E/
  Group F  C ≈ 1×10¹⁷  ~28 h each  configs/eval2/F/

FLOPs formula: C = 3 × N_LAYERS × (c_attn + c_ffn + c_router) × D
  (embedding excluded — consistent with analyze_grid.py)

W&B group: grid_eval2  (separate from phase-1 group=grid_eval)

Usage:
    python generate_eval_configs2.py
"""

import csv
import json
import math
from pathlib import Path

# ── LR scaling law ─────────────────────────────────────────────────────────────

LR_PARAMS_PATH = "results/lr_params.json"
try:
    with open(LR_PARAMS_PATH) as f:
        _p = json.load(f)
    A_ETA    = float(_p["A_eta"])
    BETA_ETA = float(_p["beta_eta"])
    print(f"Loaded LR params: A_eta={A_ETA:.4f}, beta_eta={BETA_ETA:.4f}")
except FileNotFoundError:
    print(f"WARNING: {LR_PARAMS_PATH} not found — using fallback A_eta=0.5, beta_eta=0.12")
    A_ETA    = 0.5
    BETA_ETA = 0.12

# ── Fixed architecture ──────────────────────────────────────────────────────────

N_LAYERS       = 10
SEQ_LEN        = 1024
VOCAB_SIZE     = 50280
EMBEDDING_SIZE = 50304
BATCH_TOKENS   = 8192   # 8 seqs × 1024

# Realistic P100 FP32 throughput (~10% of 10 TFLOPS peak)
P100_REALISTIC_FLOPS = 1e12   # FLOP/s

# ── Phase-2 eval points ─────────────────────────────────────────────────────────
# Format: (d_model, n_heads, G, j, C_target, group_label)
# n_heads = d_model // 64  (head_dim = 64 throughout)
# j=1 → A=12.5%, j=2 → A=25%
# G=4 → n_experts=32, G=8 → n_experts=64
#
# Scientific questions per group:
#   D: Does G=4 or G=8 beat G=1 at large d?  Width extrapolation d=768→1024.
#   E: Do rankings from D hold at 2.5× more compute?  Push to d=1280.
#   F: Stable rankings at 5× compute of D?  Is the law still predictive?

EVAL_POINTS = [
    # ── Group D: C ≈ 2×10¹⁶  (~5 h realistic per run) ───────────────────────
    # Granularity sweep at d=768, j=1: G=1 baseline vs G=4 vs G=8
    (768,  12, 1, 1, 2e16, "D"),
    (768,  12, 4, 1, 2e16, "D"),
    (768,  12, 8, 1, 2e16, "D"),
    # Width scaling at G=4, j=1: d=768 vs d=1024
    (1024, 16, 4, 1, 2e16, "D"),
    # Activation ratio test: j=2 (A=25%) at d=768, G=4
    (768,  12, 4, 2, 2e16, "D"),

    # ── Group E: C ≈ 5×10¹⁶  (~14 h realistic per run) ──────────────────────
    # Core G comparison at d=768
    (768,  12, 4, 1, 5e16, "E"),
    (768,  12, 8, 1, 5e16, "E"),
    # Width scaling: push to d=1024 and d=1280
    (1024, 16, 4, 1, 5e16, "E"),
    (1024, 16, 8, 1, 5e16, "E"),
    (1280, 20, 4, 1, 5e16, "E"),
    # Activation ratio test at larger scale
    (1024, 16, 4, 2, 5e16, "E"),

    # ── Group F: C ≈ 1×10¹⁷  (~28 h realistic per run) ──────────────────────
    # Selected configs to verify ranking stability at maximum scale
    (1024, 16, 4, 1, 1e17, "F"),
    (1024, 16, 8, 1, 1e17, "F"),
    (1280, 20, 4, 1, 1e17, "F"),
    (1280, 20, 8, 1, 1e17, "F"),
]

# ── FLOPs helpers (embedding excluded — matches analyze_grid.py) ───────────────

def m_fwd_per_token(d_model, n_experts, top_k, d_expert):
    """Forward-pass FLOPs per token (transformer stack only, no embedding)."""
    c_attn   = 8 * d_model**2 + 4 * SEQ_LEN * d_model
    c_ffn    = 6 * top_k * d_model * d_expert
    c_router = 2 * d_model * n_experts
    return N_LAYERS * (c_attn + c_ffn + c_router)


def compute_C(d_model, n_experts, top_k, d_expert, D):
    return 3 * m_fwd_per_token(d_model, n_experts, top_k, d_expert) * D


def compute_N_act(d_model, j):
    return (4 + 12 * j) * d_model**2 * N_LAYERS


def compute_N_tot(d_model, n_experts, d_expert):
    n_attn   = 4 * N_LAYERS * d_model**2
    n_ffn    = N_LAYERS * n_experts * 3 * d_model * d_expert
    n_router = N_LAYERS * d_model * n_experts
    n_embed  = EMBEDDING_SIZE * d_model
    return n_attn + n_ffn + n_router + n_embed


