#!/usr/bin/env python3
"""generate_eval_configs.py — Isocompute validation configs for scaling law testing.

For each compute budget C, multiple (d_model, G, j) configs are generated with
D chosen so that total FLOPs ≈ C.  All d_model values are > 256 (outside the
training grid) so the law is tested in extrapolation mode.

The scaling law predicts which config minimises loss at each budget.
Running all configs lets us verify empirically.

Run name format: eval_d{DIM:03d}_G{G:02d}_A{j}_S{steps}
  (S encodes the step count, from which D = steps × BATCH_TOKENS is recovered)

Usage:
    python generate_eval_configs.py
"""

import csv
import json
import math
from pathlib import Path

# ── LR scaling law ─────────────────────────────────────────────────────────────

LR_PARAMS_PATH = "results/lr_params.json"
try:
    with open(LR_PARAMS_PATH) as f:
        _p = json.load(f)
    A_ETA    = float(_p["A_eta"])
    BETA_ETA = float(_p["beta_eta"])
    print(f"Loaded LR params: A_eta={A_ETA}, beta_eta={BETA_ETA}")
except FileNotFoundError:
    print(f"WARNING: {LR_PARAMS_PATH} not found — using fallback A_eta=0.5, beta_eta=0.12")
    A_ETA    = 0.5
    BETA_ETA = 0.12

# ── Fixed architecture ──────────────────────────────────────────────────────────

N_LAYERS       = 10
SEQ_LEN        = 1024
VOCAB_SIZE     = 50280
EMBEDDING_SIZE = 50304
BATCH_TOKENS   = 8192   # 8 seqs × 1024  (must match generate_grid_configs.py)

# ── Compute budgets and eval points ────────────────────────────────────────────
# Each entry: (d_model, n_heads, G, j, C_target, budget_label)
# n_heads chosen so head_dim = d_model // n_heads = 64 (standard).
# d_model > 256 throughout → outside the training domain.

EVAL_POINTS = [
    # ── Budget A: C ≈ 2×10¹⁵ FLOPs ──────────────────────────────────────────
    # Vary d_model at fixed j=1 → isocompute N-D tradeoff curve
    (320, 5, 1, 1, 2e15, "A"),
    (384, 6, 1, 1, 2e15, "A"),
    (512, 8, 1, 1, 2e15, "A"),
    # Same d=320, higher activation ratio j=2 → does more top_k help?
    (320, 5, 1, 2, 2e15, "A"),

    # ── Budget B: C ≈ 5×10¹⁵ FLOPs ──────────────────────────────────────────
    (320, 5, 1, 1, 5e15, "B"),
    (384, 6, 1, 1, 5e15, "B"),
    (512, 8, 1, 1, 5e15, "B"),
    # Test granularity at d=384: G=2 vs G=1 at same j
    (384, 6, 2, 1, 5e15, "B"),

    # ── Budget C: C ≈ 1×10¹⁶ FLOPs ──────────────────────────────────────────
    (384, 6, 1, 1, 1e16, "C"),
    (512, 8, 1, 1, 1e16, "C"),
    # Granularity effect at larger scale
    (512, 8, 2, 1, 1e16, "C"),
    # Higher A at d=384
    (384, 6, 1, 2, 1e16, "C"),
]

# ── FLOPs helpers ──────────────────────────────────────────────────────────────

def m_fwd_per_token(d_model, n_experts, top_k, d_expert):
    """Forward-pass FLOPs per token (without ×3 fwd+bwd factor)."""
    c_attn   = 8 * d_model**2 + 4 * SEQ_LEN * d_model
    c_ffn    = 6 * top_k * d_model * d_expert
    c_router = 2 * d_model * n_experts
    return N_LAYERS * (c_attn + c_ffn + c_router) + 2 * d_model * VOCAB_SIZE


def compute_C(d_model, n_experts, top_k, d_expert, D):
    return 3 * m_fwd_per_token(d_model, n_experts, top_k, d_expert) * D


def compute_N_act(d_model, j):
    return (4 + 12 * j) * d_model**2 * N_LAYERS


def compute_N_tot(d_model, n_experts, d_expert):
    n_attn   = 4 * N_LAYERS * d_model**2
    n_ffn    = N_LAYERS * n_experts * 3 * d_model * d_expert
    n_router = N_LAYERS * d_model * n_experts
    n_embed  = EMBEDDING_SIZE * d_model
    return n_attn + n_ffn + n_router + n_embed

