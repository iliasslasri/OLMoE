# ── Main ───────────────────────────────────────────────────────────────────────

def main():
    out_dir = Path("configs/eval")
    out_dir.mkdir(parents=True, exist_ok=True)

    P100_FP32_FLOPS = 10e12
    manifest_rows   = []
    total_gpu_hours = 0.0

    print(f"\n{'run_name':<40} {'d':>4} {'G':>3} {'j':>2} {'A':>6} "
          f"{'steps':>6} {'C_actual':>12} {'lr':>10} {'budget':>7}")
    print("-" * 100)

    seen = set()
    for d_model, n_heads, G, j, C_target, budget_label in EVAL_POINTS:
        n_experts = 8 * G
        top_k     = j * G
        d_expert  = (4 * d_model) // G
        A         = j / 8

        # D is derived so that actual FLOPs ≈ C_target
        m_fwd = m_fwd_per_token(d_model, n_experts, top_k, d_expert)
        D_raw = C_target / (3 * m_fwd)
        steps = max(10, int(D_raw // BATCH_TOKENS))
        D     = steps * BATCH_TOKENS

        warmup   = max(10, math.ceil(0.01 * steps))
        C_actual = compute_C(d_model, n_experts, top_k, d_expert, D)
        lr       = A_ETA * C_actual ** (-BETA_ETA)
        N_act    = compute_N_act(d_model, j)
        N_tot    = compute_N_tot(d_model, n_experts, d_expert)

        # run_name encodes steps so analyze_grid.py can recover D = steps × BATCH_TOKENS
        run_name  = f"eval_d{d_model:03d}_G{G:02d}_A{j}_S{steps}"

        if run_name in seen:
            print(f"  [skip duplicate] {run_name}")
            continue
        seen.add(run_name)

        yaml_path = out_dir / f"{run_name}.yml"
        yaml_path.write_text(YAML_TEMPLATE.format(
            run_name=run_name, budget_label=budget_label, C_target=C_target,
            d_model=d_model, n_heads=n_heads,
            N_LAYERS=N_LAYERS, SEQ_LEN=SEQ_LEN,
            VOCAB_SIZE=VOCAB_SIZE, EMBEDDING_SIZE=EMBEDDING_SIZE,
            G=G, j=j, A=A,
            n_experts=n_experts, top_k=top_k, d_expert=d_expert,
            steps=steps, warmup=warmup,
            C_actual=C_actual, lr=lr, N_act=N_act, N_tot=N_tot,
        ))

        gpu_hours = (C_actual / P100_FP32_FLOPS) / 3600
        total_gpu_hours += gpu_hours

        manifest_rows.append(dict(
            run_name=run_name, budget=budget_label, C_target=C_target,
            d_model=d_model, n_heads=n_heads, G=G, j=j, A=A,
            top_k=top_k, n_experts=n_experts, d_expert=d_expert,
            N_act=N_act, N_tot=N_tot, D=D,
            steps=steps, warmup=warmup, C_actual=C_actual, lr=lr,
        ))
        print(f"{run_name:<40} {d_model:>4} {G:>3} {j:>2} {A:>6.1%} "
              f"{steps:>6} {C_actual:>12.3e} {lr:>10.4e} {budget_label:>7}")

    manifest_path = out_dir / "manifest.csv"
    fields = ["run_name", "budget", "C_target", "d_model", "n_heads",
              "G", "j", "A", "top_k", "n_experts", "d_expert",
              "N_act", "N_tot", "D", "steps", "warmup", "C_actual", "lr"]
    with open(manifest_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(manifest_rows)

    print(f"\nWrote {len(manifest_rows)} eval configs → {out_dir}/")
    print(f"Wrote manifest → {manifest_path}")
    print(f"Total estimated GPU-hours (P100 fp32 peak): {total_gpu_hours:.1f} h")
    print(f"Realistic estimate (~10x below peak): ~{total_gpu_hours*10:.0f} h")

    # Print isocompute groups for sanity check
    print("\nIsocompute groups (configs at same C_target):")
    by_budget = {}
    for r in manifest_rows:
        by_budget.setdefault(r["budget"], []).append(r)
    for bl in sorted(by_budget):
        print(f"  Budget {bl} (C_target={by_budget[bl][0]['C_target']:.1e}):")
        for r in by_budget[bl]:
            print(f"    d={r['d_model']}  G={r['G']}  j={r['j']}  "
                  f"steps={r['steps']}  C_actual={r['C_actual']:.3e}  "
                  f"N_act={r['N_act']:.2e}")


if __name__ == "__main__":
    main()
